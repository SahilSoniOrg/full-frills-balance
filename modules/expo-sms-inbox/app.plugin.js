const fs = require('node:fs/promises');
const path = require('node:path');
const { IOSConfig, withDangerousMod, withXcodeProject } = require('expo/config-plugins');

const { addBuildSourceFileToGroup, getApplicationNativeTarget, getProjectName } =
  IOSConfig.XcodeUtils;
const sourceName = 'ShortcutSmsCaptureIntent.swift';
const moduleSource = path.join(__dirname, 'app-intents', sourceName);

module.exports = function withShortcutSmsCapture(config) {
  config = withDangerousMod(config, [
    'ios',
    async modConfig => {
      const { projectRoot, platformProjectRoot } = modConfig.modRequest;
      const destination = path.join(platformProjectRoot, getProjectName(projectRoot), sourceName);
      const source = await fs.readFile(moduleSource, 'utf8');
      await fs.writeFile(
        destination,
        `// Generated by Expo prebuild from modules/expo-sms-inbox/app-intents/${sourceName}.\n\n${source}`,
      );
      return modConfig;
    },
  ]);

  return withXcodeProject(config, modConfig => {
    const project = modConfig.modResults;
    const { projectRoot, platformProjectRoot } = modConfig.modRequest;
    const projectName = getProjectName(projectRoot);
    const filepath = `${projectName}/${sourceName}`;

    const externalReference = project.hasFile(path.relative(platformProjectRoot, moduleSource));
    if (externalReference) {
      externalReference.path = filepath;
      externalReference.sourceTree = '"<group>"';
      return modConfig;
    }
    if (project.hasFile(filepath)) return modConfig;

    const target = getApplicationNativeTarget({ project, projectName });
    addBuildSourceFileToGroup({
      filepath,
      groupName: projectName,
      project,
      targetUuid: target.uuid,
    });
    return modConfig;
  });
};
