// Native zstd gate passed on both simulated targets before this generator was enabled.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { root, readDictionaryArtifacts, sha256 } from './dictionary-pipeline.mjs';

export const INTENDED_LOOKUP_INTERFACE =
  'lookupRowDictionary(std::string_view)->std::span<const std::uint8_t>';
export async function embedDictionaries({ check = false } = {}) {
  const artifacts = await readDictionaryArtifacts();
  // The committed C++ arrays must match every retained dictionary byte.
  const arrays = artifacts
    .map((entry, index) => {
      const lines = [];
      for (let offset = 0; offset < entry.bytes.length; offset += 16)
        lines.push(
          `  ${[...entry.bytes.subarray(offset, offset + 16)].map(byte => `0x${byte.toString(16).padStart(2, '0')}`).join(', ')},`,
        );
      return `// ${entry.id}; sha256=${sha256(entry.bytes)}\nconstexpr std::uint8_t dictionary_${index}[] = {\n${lines.join('\n')}\n};`;
    })
    .join('\n\n');
  const cases = artifacts
    .map(
      (entry, index) =>
        `  if (id == "${entry.id}") return std::span<const std::uint8_t>(dictionary_${index});`,
    )
    .join('\n');
  const source = `// Generated by scripts/sync/embed-dictionaries.mjs. Do not edit.\n#include "RowDictionaries.hpp"\n\nnamespace ffb::rows {\nnamespace {\n${arrays}\n}\n\nstd::span<const std::uint8_t> lookupRowDictionary(std::string_view id) {\n${cases}\n  return {};\n}\n} // namespace ffb::rows\n`;
  const target = resolve(root, 'modules/expo-key-crypto/cpp/RowDictionaries.cpp');
  if (check) {
    if ((await readFile(target, 'utf8')) !== source) throw new Error('Embedded dictionary drift');
  } else await writeFile(target, source);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (
    args.some(arg => !['--write', '--check'].includes(arg)) ||
    args.includes('--check') === args.includes('--write')
  )
    throw new Error('Use --write OR --check');
  await embedDictionaries({ check: args.includes('--check') });
}
